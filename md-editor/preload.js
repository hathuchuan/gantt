const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  readPath: (p) => ipcRenderer.invoke('file:read', p),
  save: (content) => ipcRenderer.invoke('file:save', content),
  saveAs: (content) => ipcRenderer.invoke('file:save-as', content),
  confirmDiscard: () => ipcRenderer.invoke('doc:confirm-discard'),
  setState: (state) => ipcRenderer.send('doc:state', state),
  closeNow: () => ipcRenderer.send('win:close-now'),
  getThemePref: () => ipcRenderer.invoke('ui:get-theme-pref'),
  setThemePref: (pref) => ipcRenderer.send('ui:theme-pref', pref),
  openExternal: (url) => ipcRenderer.send('shell:open', url),
  pathForFile: (file) => webUtils.getPathForFile(file),
  loadCommands: () => ipcRenderer.invoke('commands:load'),
  setDisabledCommands: (keys) => ipcRenderer.invoke('commands:set-disabled', keys),
  openCommandsFile: () => ipcRenderer.invoke('commands:open-file'),
  ganttBlocks: (opts) => ipcRenderer.invoke('gantt:blocks', opts),
  ganttBlock: (block) => ipcRenderer.invoke('gantt:block', block),
  ganttProjectNotes: (info) => ipcRenderer.invoke('gantt:project-notes', info),
  saveImage: (info) => ipcRenderer.invoke('image:save', info),
  exportPdf: (info) => ipcRenderer.invoke('export:pdf', info),
  exportDocx: (info) => ipcRenderer.invoke('export:docx', info),
  ganttOpen: (block) => ipcRenderer.invoke('gantt:open', block),
  ganttLink: (info) => ipcRenderer.invoke('gantt:link', info),
  ganttUnlink: (block) => ipcRenderer.invoke('gantt:unlink', block),
  notesSearch: (opts) => ipcRenderer.invoke('notes:search', opts),
  notesBacklinks: (info) => ipcRenderer.invoke('notes:backlinks', info),
  notesNames: (info) => ipcRenderer.invoke('notes:names', info),
  notesResolve: (info) => ipcRenderer.invoke('notes:resolve', info),
  notesOpen: (info) => ipcRenderer.invoke('notes:open', info),
  notesOpenLink: (info) => ipcRenderer.invoke('notes:open-link', info),
  chooseNotesFolder: () => ipcRenderer.invoke('notes:choose-folder'),
  takeJump: () => ipcRenderer.invoke('doc:take-jump'),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, action, payload) => cb(action, payload)),
});
